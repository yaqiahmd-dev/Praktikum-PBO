package Praktikum2;

public class MengubahString{
    public static void main(String[]args){
        String a = "Saya Belajar Java";
        String b = "Saya Belajar Java";

        System.out.println("===Manipulasi String===");
        System.out.println("Original a : " + a);
        System.out.println("Menjadi    : " + a.toLowerCase());
        System.out.println("\nOriginal b : " + b);
        System.out.println("Menjadi    : " + b.toUpperCase());
    }
}
